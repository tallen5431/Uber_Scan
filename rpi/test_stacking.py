# A scanner that puts one offer on the record, then keeps sending readings of a
# second card for the rest of the run. The second card is what gets measured
# against the first once the first has been marked as taken.
#
# The reading is GENERATED BY THE REAL emit(), not written out here, and that is
# the whole point of this block rather than a tidiness preference.
#
# It used to be a literal, and it carried `target` and `band` — fields the real
# scanner did not send. Advice.stack takes the target from the reading and falls
# back to ZERO when it is not a number, and `worst >= 0` is true of almost every
# pair, so on the actual rig the stack line was painted GREEN, "take both", for
# pairs that lose money against simply finishing the order already in the car.
# This suite passed the whole time, because the fixture supplied the very field
# whose absence was the defect. The same literal never noticed that `dropoff`
# was missing either, so sameArea() was asked about undefined on every real
# reading and `ends` and `route` were permanently null — the town rule, the ZIP
# rule and the map link had never once fired in a car.
#
# A hand-written fixture can drift from the program it stands in for. This
# cannot: if a field the server needs stops being emitted, the end-to-end
# assertions below go wrong, which is exactly what should have happened.
#
# Which offer is on the record is driven from a file the test writes, so the
# sequence is deterministic rather than a race against a sleep. Several of the
# properties below are about what happens when the offer on screen is no longer
# the one in the car, and that cannot be reached at all with a scanner that only
# ever names one.
QUEUE = os.path.join(work, 'next')
# ...and the destination read off the screen AFTER the accept, on its own queue.
