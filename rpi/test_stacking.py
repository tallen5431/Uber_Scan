def put_dropoff(tag):
    """Make the scanner say it read a destination, once."""
    tmp = DROP + '.part'
    with open(tmp, 'w') as fh:
        fh.write(tag)
    os.replace(tmp, DROP)


def put_offer(offer):
    """Make this the offer on the record, and wait until the server has it."""
    tmp = QUEUE + '.part'
    with open(tmp, 'w') as fh:
        fh.write(json.dumps(offer))
    os.replace(tmp, QUEUE)
    for _ in range(100):
        on = get(base, '/api/status').get('offer')
        if on and on.get('id') == offer['id']:
            return True
        time.sleep(0.1)
    return False


